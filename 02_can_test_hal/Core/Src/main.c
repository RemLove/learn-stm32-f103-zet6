  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_CAN_Init();
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */

  printf("\r\n========== CAN 回环测试 ==========\r\n");
  printf("模式: 静默回环, 波特率 100kbps\r\n\r\n");

  FilterConfig();

  if (HAL_CAN_Start(&hcan) != HAL_OK)
  {
    printf("CAN 启动失败!\r\n");
    Error_Handler();
  }
  printf("CAN 启动成功\r\n\r\n");

