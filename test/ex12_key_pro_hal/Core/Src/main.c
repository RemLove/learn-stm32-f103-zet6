/* USER CODE BEGIN 4 */
void Key_Task(void)
{
  //1.消抖
  uint8_t Key_now=HAL_GPIO_ReadPin(GPIOE,GPIO_PIN_4);//PE4
  if(Key_now!=Key_last)
  {
    Key_last=Key_now;
    Key_time=HAL_GetTick();
  }
  if((HAL_GetTick()-Key_time)>10)//10ms消抖
  {
    Key_stable=Key_now;
  }
  //2.按键状态机
  switch (Keystatus)
  {
  case S_IDLE:
    if(Key_stable==0)//按下
    {
      Keystatus=S_DOWN;
      Key_down_time=HAL_GetTick();
    }
    break;
    case S_DOWN:
    if(Key_stable==1)//松开
    {
      Keystatus=S_IDLE;
      HAL_GPIO_TogglePin(GPIOB,GPIO_PIN_5);//LED0翻转
      printf("短按\r\n");
      //短按事件
    }
    else if((HAL_GetTick()-Key_down_time)>2000)//长按
    {
      Keystatus=S_LONG;
      HAL_GPIO_TogglePin(GPIOE,GPIO_PIN_5);//LED1翻转
      printf("长按\r\n");
      //长按事件
    }
    break;
    case S_LONG:
    if(Key_stable==1)//松开
    {
      Keystatus=S_IDLE;
    }
    break;
  }
}
